"""Quality gates for video/out/cardiolens_demo_1080p.mp4.

1 duration 8:30-9:45 · 2 coverage (COVERAGE.md, every A/B item timestamped) · 3 one frame every 10 s + contact
sheet (for a human/AI look) · 4 loudness -14 +-1 LUFS, true peak <= -1 dBTP, no silence > 4 s outside the cold
open / end card · also writes youtube_description.md chapter timestamps.
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from coverage_map import COVERAGE, VISUAL  # noqa: E402
from script import VIDEO  # noqa: E402

OUT = VIDEO / "out"
MP4 = OUT / "cardiolens_demo_1080p.mp4"
QA = VIDEO / "qa"
TL = json.loads((VIDEO / "editor" / "src" / "timeline.gen.json").read_text(encoding="utf-8"))
FPS = TL["fps"]


def ts(sec: float) -> str:
    return f"{int(sec // 60)}:{int(sec % 60):02d}"


def probe(p: Path) -> dict:
    r = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration:stream=codec_name,width,height,r_frame_rate,pix_fmt,bit_rate,profile",
                        "-of", "json", str(p)], capture_output=True, text=True, check=True)
    return json.loads(r.stdout)


def scene_time(sid: str, ref) -> float | None:
    sc = next((s for s in TL["scenes"] if s["id"] == sid), None)
    if not sc:
        return None
    base = sc["start"] / FPS
    if isinstance(ref, (int, float)):
        return base + ref
    if ref.startswith("mark:"):
        for c in sc["clips"]:
            m = next((m for m in c["marks"] if m["name"] == ref[5:]), None)
            if m:
                return base + m["t"]
        return base
    return base + sc["cues"].get(ref, 0.0)


def coverage() -> tuple[int, int]:
    inv = (VIDEO / "FEATURE_INVENTORY.md").read_text(encoding="utf-8")
    items = re.findall(r"^\| ([A-Z]\d+) \| (.+?) \| .+? \| .+? \| ([ABC]) \|$", inv, flags=re.M)
    rows, ok = [], 0
    for iid, name, imp in items:
        c = COVERAGE.get(iid)
        t = scene_time(c[0], c[1]) if c else None
        if t is not None:
            ok += 1
        rows.append(f"| {iid} | {imp} | {name} | {ts(t) if t is not None else '—'} | {c[0] if c else '—'} | {c[2] if c else 'MISSING'} |")
    (VIDEO / "COVERAGE.md").write_text(
        "# Coverage: inventory item → where it appears in the final video\n\n"
        f"Generated by `video/pipeline/qa.py` from the render timeline. {ok}/{len(items)} items placed "
        f"({sum(1 for i in items if i[2] in 'AB')} A/B items, {sum(1 for i in items if i[2] == 'C')} C items).\n\n"
        "| # | Imp. | Item | Time | Scene | How |\n|---|---|---|---|---|---|\n" + "\n".join(rows) + "\n", encoding="utf-8")
    by_scene: dict[str, list[str]] = {}
    for iid, name, imp in items:
        if iid in COVERAGE:
            by_scene.setdefault(COVERAGE[iid][0], []).append(f"{iid}({imp})")
    sb = ["# Storyboard (generated from the render timeline)", "",
          "Chapters match `video/NARRATION.md`; the narration text lives there.", "",
          "| Time | Scene | Visual | Inventory items |", "|---|---|---|---|"]
    for s in TL["scenes"]:
        sb.append(f"| {ts(s['start'] / FPS)}–{ts((s['start'] + s['duration']) / FPS)} | {s['id']} · {s['title']} | {VISUAL.get(s['id'], '')} | {' '.join(by_scene.get(s['id'], []))} |")
    (VIDEO / "STORYBOARD.md").write_text(chr(10).join(sb) + chr(10), encoding="utf-8")
    ab = [i for i in items if i[2] in "AB"]
    ab_ok = sum(1 for i in ab if COVERAGE.get(i[0]) and scene_time(COVERAGE[i[0]][0], COVERAGE[i[0]][1]) is not None)
    return ab_ok, len(ab)


def frames(duration: float) -> None:
    fdir = QA / "frames"
    fdir.mkdir(parents=True, exist_ok=True)
    for old in fdir.glob("*.jpg"):
        old.unlink()
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(MP4), "-vf", "fps=1/10", "-q:v", "3", str(fdir / "f_%03d.jpg")], check=True)
    n = len(list(fdir.glob("*.jpg")))
    rows = (n + 5) // 6
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(MP4), "-vf", f"fps=1/10,scale=480:-2,tile=6x{rows}:padding=4:color=white",
                    "-frames:v", "1", str(QA / "contact_sheet.png")], check=True)
    print(f"frames: {n} (every 10 s) -> {fdir}; contact sheet -> {QA / 'contact_sheet.png'}")


def audio(duration: float) -> dict:
    r = subprocess.run(["ffmpeg", "-hide_banner", "-nostats", "-i", str(MP4), "-af", "ebur128=peak=true", "-f", "null", "-"],
                       capture_output=True, text=True)
    summ = r.stderr[r.stderr.rfind("Summary:"):]
    i = float(re.search(r"I:\s+(-?[\d.]+) LUFS", summ).group(1))
    tp = float(re.search(r"Peak:\s+(-?[\d.]+) dBFS", summ).group(1))
    r = subprocess.run(["ffmpeg", "-hide_banner", "-nostats", "-i", str(MP4), "-af", "silencedetect=noise=-50dB:d=4", "-f", "null", "-"],
                       capture_output=True, text=True)
    sil = [(float(a), float(b)) for a, b in re.findall(r"silence_start: ([\d.]+)[\s\S]*?silence_end: ([\d.]+)", r.stderr)]
    end_card = duration - 6.5
    bad = [(a, b) for a, b in sil if not (b <= 5.0 or a >= end_card)]
    return {"lufs": i, "true_peak": tp, "long_silences": bad}


def chapters() -> list[tuple[float, str]]:
    names = {c["chapter"]: c["title"] for c in TL["chapterCards"]}
    out = [(0.0, "Cold open")]
    for c in TL["chapterCards"]:
        out.append((c["start"] / FPS, names[c["chapter"]]))
    return out


