def main() -> None:
    p = probe(MP4)
    dur = float(p["format"]["duration"])
    ab_ok, ab_n = coverage()
    frames(dur)
    au = audio(dur)
    gates = {
        "1 duration 8:30-9:45": (510 <= dur <= 585, f"{ts(dur)} ({dur:.1f} s)"),
        "2 coverage A/B": (ab_ok == ab_n, f"{ab_ok}/{ab_n}"),
        "4 loudness -14 +-1 LUFS": (abs(au["lufs"] + 14) <= 1, f"{au['lufs']} LUFS"),
        "4 true peak <= -1 dBTP": (au["true_peak"] <= -0.9, f"{au['true_peak']} dBTP"),
        "4 no silence > 4 s": (not au["long_silences"], str(au["long_silences"])),
    }
    v = next(s for s in p["streams"] if s["codec_name"] == "h264")
    a = next(s for s in p["streams"] if s["codec_name"] == "aac")
    report = {"file": str(MP4), "video": v, "audio": a, "chapters": [(ts(t), n) for t, n in chapters()],
              "gates": {k: {"pass": ok, "value": val} for k, (ok, val) in gates.items()}}
    (QA / "qa_report.json").write_text(json.dumps(report, indent=1), encoding="utf-8")
    for k, (ok, val) in gates.items():
        print(("PASS " if ok else "FAIL ") + k + ": " + val)
    youtube(chapters())
    print("chapters:", report["chapters"])


if __name__ == "__main__":
    main()
